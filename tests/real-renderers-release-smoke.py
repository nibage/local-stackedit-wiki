#!/usr/bin/env python3
"""End-to-end test of *genuine* bundled renderers in an offline release ZIP.

Not a stub test: run against an archive generated by build-offline-release.py.
Requires Playwright and a local Chromium installation. Every HTTP request is
intercepted and served from the extracted archive; external network is rejected.
"""
import argparse
import json
import mimetypes
import unicodedata
import xml.etree.ElementTree as ET
from pathlib import Path
import tempfile
from urllib.parse import unquote, urlsplit
import zipfile

from playwright.sync_api import sync_playwright

ORIGIN = 'https://local-wiki.test'


def prepare_root(zip_path, output):
    with zipfile.ZipFile(zip_path) as archive:
        bad = archive.testzip()
        if bad:
            raise AssertionError(f'Poškozený soubor ZIP: {bad}')
        allow_root = {'index.html'}
        allow_dirs = {'src', 'assets', 'vendor'}
        allow_images = set()
        shipped=set()
        for info in archive.infolist():
            target = output / info.filename
            if not target.resolve().is_relative_to(output.resolve()):
                raise AssertionError('Nebezpečná cesta v ZIPu')
            parts=Path(info.filename).parts
            relative=Path(*parts[1:]).as_posix()
            if not relative or not (relative in allow_root or relative in allow_images or
                   Path(relative).parts[0] in allow_dirs):
                raise AssertionError('Development-only file leaked into user ZIP: '+relative)
            shipped.add(relative)
        if not (allow_root | allow_images).issubset(shipped):
            raise AssertionError('Essential offline entry point missing from ZIP')
        archive.extractall(output)
    matches = list(output.glob('*/index.html'))
    if len(matches) != 1:
        raise AssertionError('ZIP musí obsahovat jedinou kořenovou aplikaci s index.html')
    return matches[0].parent


def run(root, browser_path=None):
    root = Path(root).resolve()
    assert (root / 'index.html').is_file(), 'Chybí index.html'
    assert (root / 'vendor/mermaid/mermaid.min.js').stat().st_size > 100_000, 'Chybí originální Mermaid'
    assert (root / 'vendor/abcjs/abcjs-basic-min.js').stat().st_size > 50_000, 'Chybí originální ABCjs'
    failures = []
    with sync_playwright() as playwright:
        kwargs = {'headless': True, 'args': ['--no-sandbox']}
        if browser_path:
            kwargs['executable_path'] = browser_path
        browser = playwright.chromium.launch(**kwargs)
        page = browser.new_page(viewport={'width': 1200, 'height': 820}, accept_downloads=True)
        page.on('pageerror', lambda exc: failures.append('JS: ' + str(exc)))

        def local_files(route):
            requested = urlsplit(route.request.url)
            if requested.scheme != 'https' or requested.netloc != 'local-wiki.test':
                failures.append('Pokus o externí síťový požadavek: ' + route.request.url)
                route.abort()
                return
            path = unquote(requested.path).lstrip('/') or 'index.html'
            file_path = (root / path).resolve()
            if not file_path.is_relative_to(root) or not file_path.is_file():
                failures.append('Chybějící lokální soubor: ' + path)
                route.fulfill(status=404, body='Not found')
                return
            mime = mimetypes.guess_type(file_path.name)[0] or 'application/octet-stream'
            route.fulfill(status=200, content_type=mime, body=file_path.read_bytes())

        page.route('**/*', local_files)
        # The test environment may prohibit top-level navigation. Loading the
        # same HTML with a local asset base works without an HTTP server.
        html = (root / 'index.html').read_text(encoding='utf-8')
        html = html.replace('<head>', '<head><base href="https://local-wiki.test/">', 1)
        page.set_content(html, wait_until='load', timeout=30000)
        page.wait_for_function('Boolean(window.LocalWikiRender && window.LocalWikiRendererSmoke)', timeout=12000)
        caps = page.evaluate('window.LocalWikiDiagrams.capabilities()')
        assert caps == {'mermaid': True, 'abc': True}, f'UMD knihovny se nenačetly: {caps}'
        page.locator('#renderer-check').click()
        assert page.locator('#renderer-repair-tools').is_hidden(), 'Fully bundled release must not advertise installation'
        assert page.locator('#renderer-ready-note').is_visible()
        assert page.locator('#renderer-details .renderer-detail').count()==4
        page.locator('#renderer-close').click()
        result = page.evaluate('window.LocalWikiRendererSmoke.run({timeoutMs:12000})')
        for kind in ('mermaid', 'abc'):
            assert result[kind]['status'] == 'ok', f'{kind}: neprošel skutečný SVG self-test: {result[kind]}'

        # Exercise the real preview pipeline and adapter, not just the libraries.
        markdown = ('# Ověření\n\n```mermaid\ngraph TD\n  A[První] --> B[Druhý]\n```\n\n'
                    '```abc\nX:1\nT:Ověření\nM:4/4\nL:1/4\nK:C\nC D E F | G4 |\n```\n\nSelect this formula: $E=mc^2$\n')
        page.evaluate('''(md) => {
            const area = document.createElement('div');
            area.id = 'release-preview';
            document.body.appendChild(area);
            window.LocalWikiRender.render(md, area, {});
        }''', markdown)
        page.wait_for_function('''() => {
            const preview = document.querySelector('#release-preview');
            return preview && preview.querySelectorAll('.visualization-mermaid svg').length === 1 &&
                preview.querySelectorAll('.visualization-abc svg').length === 1;
        }''', timeout=15000)
        assert not page.locator('#release-preview .visualization svg script').count(), 'SVG obsahuje script'
        # Unlike the old SVG output, native MathML contains actual selectable text.
        page.wait_for_function("""() =>
            document.querySelector('#release-preview .MathJax_MathML math mi') !== null
        """,timeout=20000)
        selection = page.evaluate("""() => {
            const math = document.querySelector('#release-preview .MathJax_MathML math');
            const range = document.createRange();
            range.selectNodeContents(math);
            const selection = window.getSelection();
            selection.removeAllRanges(); selection.addRange(range);
            const text = selection.toString();
            selection.removeAllRanges();
            return text;
        }""")
        normalized = unicodedata.normalize('NFKC', selection)
        assert 'E' in normalized and 'm' in normalized and 'c' in normalized, normalized
        # Real mouse drag over the formula must also select visible mathematical glyphs.
        formula = page.locator('#release-preview .MathJax_MathML math').first
        box = formula.bounding_box()
        assert box and box['width'] > 15, box
        y = box['y'] + box['height'] / 2
        page.mouse.move(box['x'] + 2, y)
        page.mouse.down()
        page.mouse.move(box['x'] + box['width'] - 2, y, steps=24)
        page.mouse.up()
        mouse_selection = unicodedata.normalize('NFKC',
            page.evaluate("window.getSelection().toString()"))
        assert mouse_selection.strip(), 'MathML formula cannot be selected by mouse'

        # MathJax's contextual math menu must remain registered.
        assert page.evaluate("Boolean(window.MathJax && MathJax.Extension.MathMenu)"), 'MathMenu unavailable'

        for kind in ('mermaid', 'abc'):
            with page.expect_download(timeout=10000) as pending:
                page.locator(f'#release-preview .visualization-{kind} .diagram-export').click()
            exported = pending.value
            assert exported.suggested_filename.startswith(kind + '-') and exported.suggested_filename.endswith('.svg')
            exported_path = exported.path()
            xml = exported_path.read_text(encoding='utf-8')
            root_svg = ET.fromstring(xml)
            assert root_svg.tag == '{http://www.w3.org/2000/svg}svg', f'{kind}: není platné SVG'
            assert len(xml) > 400 and len(list(root_svg.iter())) > 5, f'{kind}: prázdný export'
            if kind == 'abc':
                assert root_svg.get('width') and root_svg.get('height'), 'ABC SVG musí mít samostatné rozměry'
                assert any(element.tag.endswith('path') for element in root_svg.iter()), 'ABC SVG neobsahuje notové glyfy'
        # The MathJax right-click source menu must actually open, not just load.
        page.evaluate("window.getSelection().removeAllRanges()")
        page.locator('#release-preview .MathJax_MathML').first.click(button='right')
        page.wait_for_function("""() => {
            const menu=document.querySelector('.MathJax_ContextMenu');
            return menu && getComputedStyle(menu).display !== 'none';
        }""",timeout=5000)
        assert not failures, json.dumps(failures, ensure_ascii=False)
        browser.close()
    return result


def main():
    parser = argparse.ArgumentParser(description='Reálný offline smoke test Mermaid/ABCjs uvnitř distribučního ZIPu')
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--zip', type=Path, dest='zip_path')
    group.add_argument('--root', type=Path)
    parser.add_argument('--chromium', help='Cesta k lokální instalaci Chromia (volitelné)')
    args = parser.parse_args()
    if args.zip_path:
        with tempfile.TemporaryDirectory(prefix='local-wiki-smoke-') as tmp:
            result = run(prepare_root(args.zip_path, Path(tmp)), args.chromium)
    else:
        result = run(args.root, args.chromium)
    print('OK: Mermaid a ABCjs fungují offline a oba stahují platné samostatné SVG soubory')
    print(json.dumps(result, ensure_ascii=False))


if __name__ == '__main__':
    main()
