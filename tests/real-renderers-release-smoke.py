#!/usr/bin/env python3
"""End-to-end test of *genuine* bundled renderers in an offline release ZIP.

Not a stub test: run against an archive generated by build-offline-release.py.
Requires Playwright and a local Chromium installation. Every HTTP request is
intercepted and served from the extracted archive; external network is rejected.
"""
import argparse
import json
import mimetypes
from pathlib import Path
import tempfile
from urllib.parse import unquote, urlsplit
import zipfile

from playwright.sync_api import sync_playwright

ORIGIN = 'https://local-wiki.test'


def prepare_root(zip_path, output):
    with zipfile.ZipFile(zip_path) as archive:
        bad = archive.testzip()
        if bad:
            raise AssertionError(f'Poškozený soubor ZIP: {bad}')
        for info in archive.infolist():
            target = output / info.filename
            if not target.resolve().is_relative_to(output.resolve()):
                raise AssertionError('Nebezpečná cesta v ZIPu')
        archive.extractall(output)
    matches = list(output.glob('*/index.html'))
    if len(matches) != 1:
        raise AssertionError('ZIP musí obsahovat jedinou kořenovou aplikaci s index.html')
    return matches[0].parent


def run(root, browser_path=None):
    root = Path(root).resolve()
    assert (root / 'index.html').is_file(), 'Chybí index.html'
    assert (root / 'vendor/mermaid/mermaid.min.js').stat().st_size > 100_000, 'Chybí originální Mermaid'
    assert (root / 'vendor/abcjs/abcjs-basic-min.js').stat().st_size > 50_000, 'Chybí originální ABCjs'
    failures = []
    with sync_playwright() as playwright:
        kwargs = {'headless': True, 'args': ['--no-sandbox']}
        if browser_path:
            kwargs['executable_path'] = browser_path
        browser = playwright.chromium.launch(**kwargs)
        page = browser.new_page(viewport={'width': 1200, 'height': 820})
        page.on('pageerror', lambda exc: failures.append('JS: ' + str(exc)))

        def local_files(route):
            requested = urlsplit(route.request.url)
            if requested.scheme != 'https' or requested.netloc != 'local-wiki.test':
                failures.append('Pokus o externí síťový požadavek: ' + route.request.url)
                route.abort()
                return
            path = unquote(requested.path).lstrip('/') or 'index.html'
            file_path = (root / path).resolve()
            if not file_path.is_relative_to(root) or not file_path.is_file():
                failures.append('Chybějící lokální soubor: ' + path)
                route.fulfill(status=404, body='Not found')
                return
            mime = mimetypes.guess_type(file_path.name)[0] or 'application/octet-stream'
            route.fulfill(status=200, content_type=mime, body=file_path.read_bytes())

        page.route('**/*', local_files)
        # The test environment may prohibit top-level navigation. Loading the
        # same HTML with a local asset base works without an HTTP server.
        html = (root / 'index.html').read_text(encoding='utf-8')
        html = html.replace('<head>', '<head><base href="https://local-wiki.test/">', 1)
        page.set_content(html, wait_until='load', timeout=30000)
        page.wait_for_function('Boolean(window.LocalWikiRender && window.LocalWikiRendererSmoke)', timeout=12000)
        caps = page.evaluate('window.LocalWikiDiagrams.capabilities()')
        assert caps == {'mermaid': True, 'abc': True}, f'UMD knihovny se nenačetly: {caps}'
        result = page.evaluate('window.LocalWikiRendererSmoke.run({timeoutMs:12000})')
        for kind in ('mermaid', 'abc'):
            assert result[kind]['status'] == 'ok', f'{kind}: neprošel skutečný SVG self-test: {result[kind]}'

        # Exercise the real preview pipeline and adapter, not just the libraries.
        markdown = ('# Ověření\n\n```mermaid\ngraph TD\n  A[První] --> B[Druhý]\n```\n\n'
                    '```abc\nX:1\nT:Ověření\nM:4/4\nL:1/4\nK:C\nC D E F | G4 |\n```\n')
        page.evaluate('''(md) => {
            const area = document.createElement('div');
            area.id = 'release-preview';
            document.body.appendChild(area);
            window.LocalWikiRender.render(md, area, {});
        }''', markdown)
        page.wait_for_function('''() => {
            const preview = document.querySelector('#release-preview');
            return preview && preview.querySelectorAll('.visualization-mermaid svg').length === 1 &&
                preview.querySelectorAll('.visualization-abc svg').length === 1;
        }''', timeout=15000)
        assert not page.locator('#release-preview .visualization svg script').count(), 'SVG obsahuje script'
        assert not failures, json.dumps(failures, ensure_ascii=False)
        browser.close()
    return result


def main():
    parser = argparse.ArgumentParser(description='Reálný offline smoke test Mermaid/ABCjs uvnitř distribučního ZIPu')
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--zip', type=Path, dest='zip_path')
    group.add_argument('--root', type=Path)
    parser.add_argument('--chromium', help='Cesta k lokální instalaci Chromia (volitelné)')
    args = parser.parse_args()
    if args.zip_path:
        with tempfile.TemporaryDirectory(prefix='local-wiki-smoke-') as tmp:
            result = run(prepare_root(args.zip_path, Path(tmp)), args.chromium)
    else:
        result = run(args.root, args.chromium)
    print('OK: skutečné Mermaid a ABCjs vytvořily SVG i v náhledu, bez síťových požadavků')
    print(json.dumps(result, ensure_ascii=False))


if __name__ == '__main__':
    main()
